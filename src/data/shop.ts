export const SHOP_CATEGORIES: readonly Category[] = CATEGORY_KEYS;

/**
 * How to read the live price off the source `url`. When unset, the
 * pricing layer leaves the static `priceRange` in place — that's the
 * default for every existing listing until the audit pass classifies
 * it. See `src/lib/pricing/fetchPrice.ts`.
 */
export type ExtractionMethod = "json-ld" | "shopify" | "html" | "manual";

export type ShopProduct = {
  slug: string;
  name: string;
  brand: string;
  /** Top-level — closed-world to keys in CATEGORY_TREE. */
  category: Category;
  /**
   * Two-level taxonomy leaf. Required since the May 2026 category
   * restructure. Free-text — values not in CATEGORY_TREE are valid
   * runtime values (datalist autocomplete is advisory).
   */
  subcategory: Subcategory;
  reason: string;
  /**
   * Manual / last-known-good price. Always rendered when no
   * `extractionMethod` is set, or as the fallback when a live fetch
   * fails. Curated by Jordan; live fetches override at runtime.
   */
  priceRange: PriceTier;
  /**
   * Cross-pillar audience tags. Lets one product appear in MENS and
   * WOMENS at the same time without duplicating the entry. Empty
   * array (or omitted) for items that don't carry a gendered
   * audience signal — those filter solely by `category`.
   *
   * Allowed values: "mens", "womens". Order doesn't matter.
   */
  audience?: ("mens" | "womens")[];
  /**
   * ISO timestamp of original import. Existing entries created
   * before this field landed are backfilled with a single baseline
   * date; new entries get `Date.now()` at import time. Used for the
   * Date added sort and the list-view DATE ADDED column.
   */
  dateAdded?: string;
  /** External product page. Doubles as the source for live pricing. */
  url: string;
  /** Renderable image URL (typically `/shop/<slug>-1.jpg`). */
  image: string;
  /**
   * Optional gallery. When present, the detail page renders a carousel.
   * The first entry should match `image` (used on the grid + metadata).
   */
  images?: string[];
  /**
   * Optional live-pricing strategy. Omit (or set to "manual") to keep
   * the static `priceRange`. The audit pass fills these in per source
   * domain.
   */
  extractionMethod?: ExtractionMethod;
  /**
   * CSS selector pointing at the priced element. Required when
   * `extractionMethod === "html"`, ignored otherwise. Supports a small
   * subset of CSS — see `extractors/html.ts` for the grammar.
   */
  htmlPriceSelector?: string;
  /**
   * Plausibility floor. Variants below this dollar amount are dropped
   * before display — the typical case is a Shopify shop that lists
   * sample swatches or replacement parts as full variants. Set this
   * just below the lowest legitimate variant of the actual product.
   */
  priceFloor?: number;
  /**
   * Staging flag for the bulk-import flow. `true` means the entry was
   * mechanically staged from the editorial audit and is awaiting human
   * promotion via /admin/shop-drafts. Drafts are filtered out of every
   * public read path (pillar pages, /shop, /shop/[slug]) — only the
   * drafts admin sees them. Omit or set `false` for live entries.
   */
  draft?: boolean;
  /**
   * Operational stability tier — see `data/sourcing-policy.md`.
   *
   *   1 — Forever Infrastructure Brand. Stable SKUs, stable URLs,
   *       reliable structured data. Earns "skeleton of the shop"
   *       placement.
   *   2 — Stable smaller / artisan brand. Solid for the archive
   *       but secondary to Tier 1 in foundational picks.
   *   3 — Manual-polish-OK. Page loads but structured data is
   *       thin; manual image / price entry expected.
   *   4 — Editorial-mention only. Brand site is bot-walled or
   *       otherwise too unstable to be an operational dependency.
   *       Should rarely become a live Shop entry.
   *
   * Set on import via the optional CSV column; manually editable
   * via /admin/shop-edit/<slug>. Surfaces as a small label on the
   * drafts admin so reviewers can apply the policy at a glance.
   */
  stabilityTier?: 1 | 2 | 3 | 4;
  /**
   * Atmosphere collections this object belongs to. Emotional groupings
   * that cut across operational category — see CATEGORY_ATMOSPHERE_MAP
   * in the Hessentials Object Archive sheet. A single product can sit
   * inside several atmospheres at once (a titanium mug is both
   * `Morning Ritual` and `Portable Ritual`).
   *
   * Examples:
   *   ["The Anti-Hostess Table", "Weeknight Table"]
   *   ["Morning Ritual", "Portable Ritual"]
   *   ["Things That Age Correctly", "Soft Travel"]
   *
   * Empty array or omitted for products that don't anchor a specific
   * atmosphere yet.
   */
  atmosphereCollection?: string[];
  /**
   * Tier 1 emotional territory — short three-to-five-word phrase
   * inherited from the product's brand. Snow Peak's territory is
   * "soft travel / outdoor calm / analog movement"; Hawkins' is
   * "table softness / linen texture / understated hosting".
   *
   * Surfaces editorially (not enforced at type level). Storing the
   * territory on the product lets the public detail page render
   * brand atmosphere alongside category.
   */
  territoryWeather?: string;
};

