/**
 * Public lookup by slug. Skips draft entries — those are bulk-import
 * staging records, visible only to /admin/shop-drafts. Admin code that
 * needs to read drafts should walk SHOP_PRODUCTS directly.
 */
export function getProductBySlug(slug: string): ShopProduct | undefined {
  return SHOP_PRODUCTS.find((p) => p.slug === slug && p.draft !== true);
}

export function getProductsByCategory(category: ShopCategory): ShopProduct[] {
  return SHOP_PRODUCTS.filter(
    (p) => p.category === category && p.draft !== true
  );
}
